#!/bin/sh
# Exercise scripts/local-compose-env.sh in a scratch tree, never the real deploy/.
#
# The one property that matters is that the password is generated ONCE: Postgres
# fixes it when it initialises the volume, so a script that regenerates on a
# later run leaves the local stack unable to open its own database, and nothing
# says why. Every other case here is secondary to "a second run keeps it".
#
# POSIX sh, not bash: this runs in the `docker:27-cli` CI image (no bash, no
# python) alongside test-deploy-v-note.sh.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# A stub `docker` on PATH answers `volume inspect` from STUB_VOLUMES, so the
# volume guard is exercised both ways without depending on — or touching — the
# volumes that really exist on the machine running this. Unset means none.
mkdir -p "$WORK/bin"
cat > "$WORK/bin/docker" <<'STUB'
#!/bin/sh
echo "$*" >> "$DOCKER_CALLS"
if [ "$1" = "volume" ] && [ "$2" = "inspect" ]; then
  for v in ${STUB_VOLUMES:-}; do
    [ "$v" = "$3" ] && exit 0
  done
fi
exit 1
STUB
chmod +x "$WORK/bin/docker"
PATH="$WORK/bin:$PATH"
DOCKER_CALLS="$WORK/docker-calls"
STUB_VOLUMES=""
export PATH DOCKER_CALLS STUB_VOLUMES

FAILURES=0
fail() {
  echo "FAIL: $*"
  FAILURES=$((FAILURES + 1))
}
pass() {
  echo "ok: $*"
}

# A fresh tree per case: its own copy of the script (which locates deploy/ from
# its own path) and of the committed compose.env.
new_tree() {
  tree="$WORK/$1"
  mkdir -p "$tree/scripts" "$tree/deploy"
  cp "$ROOT/scripts/local-compose-env.sh" "$tree/scripts/"
  cp "$ROOT/deploy/compose.env" "$tree/deploy/"
  echo "$tree"
}

password_in() {
  sed -n 's/^POSTGRES_PASSWORD=//p' "$1" | tail -n 1
}

# --- generates a password when deploy/.env is absent ----------------------------
T=$(new_tree fresh)
if "$T/scripts/local-compose-env.sh" >/dev/null; then
  P1=$(password_in "$T/deploy/.env")
  if printf '%s' "$P1" | grep -Eq '^[0-9a-f]{48}$'; then
    pass "generates a 48-hex-char password when deploy/.env is absent"
  else
    fail "generated password is not 48 hex chars: '$P1'"
  fi
  # The file holds the only copy of a credential; it should not be world-readable.
  MODE=$(stat -c '%a' "$T/deploy/.env")
  if [ "$MODE" = "600" ]; then
    pass "deploy/.env is written mode 600"
  else
    fail "deploy/.env mode is $MODE, want 600"
  fi
else
  fail "script failed on a fresh tree"
  P1=""
fi

# --- does not regenerate when one exists ---------------------------------------
"$T/scripts/local-compose-env.sh" >/dev/null
P2=$(password_in "$T/deploy/.env")
if [ -n "$P1" ] && [ "$P1" = "$P2" ]; then
  pass "a second run keeps the password"
else
  fail "a second run changed the password ('$P1' -> '$P2')"
fi
if [ "$(grep -c '^POSTGRES_PASSWORD=' "$T/deploy/.env")" = "1" ]; then
  pass "a second run does not duplicate POSTGRES_PASSWORD"
else
  fail "POSTGRES_PASSWORD appears more than once after a second run"
fi

# --- two fresh trees get different passwords -----------------------------------
T2=$(new_tree fresh2)
"$T2/scripts/local-compose-env.sh" >/dev/null
if [ "$(password_in "$T2/deploy/.env")" != "$P1" ]; then
  pass "separate trees get separately generated passwords"
else
  fail "two fresh trees generated the same password"
fi

# --- merges compose.env, and picks up edits to it ------------------------------
MISSING=""
while IFS= read -r line; do
  case "$line" in
    '' | '#'*) continue ;;
  esac
  grep -qxF "$line" "$T/deploy/.env" || MISSING="$MISSING $line"
done < "$ROOT/deploy/compose.env"
if [ -z "$MISSING" ]; then
  pass "every compose.env assignment is carried into deploy/.env"
else
  fail "compose.env lines missing from deploy/.env:$MISSING"
fi

echo "ADDED_BY_TEST=1" >> "$T/deploy/compose.env"
"$T/scripts/local-compose-env.sh" >/dev/null
if grep -qx 'ADDED_BY_TEST=1' "$T/deploy/.env" && [ "$(password_in "$T/deploy/.env")" = "$P1" ]; then
  pass "a compose.env edit propagates and the password survives it"
else
  fail "a compose.env edit did not propagate, or it changed the password"
fi

# --- a deploy/.env from the retired store-backed script keeps working -----------
# That script wrote every stored key raw, sorted, after compose.env — so a
# password can contain `=`, `+` and `/`, and a retired key rode along with it.
T=$(new_tree legacy)
LEGACY_PW='aB3+/xY=z=='
{
  echo "# Generated by the old script — do not commit."
  cat "$ROOT/deploy/compose.env"
  echo
  echo "OIDC_CLIENT_SECRET=retired-value"
  echo "POSTGRES_PASSWORD=$LEGACY_PW"
} > "$T/deploy/.env"
"$T/scripts/local-compose-env.sh" >/dev/null
if [ "$(password_in "$T/deploy/.env")" = "$LEGACY_PW" ]; then
  pass "an existing password is kept verbatim, including = + /"
else
  fail "legacy password not kept verbatim: '$(password_in "$T/deploy/.env")'"
fi
if grep -q '^OIDC_CLIENT_SECRET=' "$T/deploy/.env"; then
  fail "a key no longer in compose.env was carried over"
else
  pass "keys that are not in compose.env are dropped"
fi

# --- an empty password is treated as absent ------------------------------------
T=$(new_tree empty)
echo "POSTGRES_PASSWORD=" > "$T/deploy/.env"
"$T/scripts/local-compose-env.sh" >/dev/null
if printf '%s' "$(password_in "$T/deploy/.env")" | grep -Eq '^[0-9a-f]{48}$'; then
  pass "an empty POSTGRES_PASSWORD is replaced with a generated one"
else
  fail "an empty POSTGRES_PASSWORD was not replaced"
fi

# --- an existing volume blocks generation --------------------------------------
# The volume name is machine-wide, so a second checkout (or a deploy/.env
# deleted on its own) must not mint a password the volume will reject.
VOLUME=$(sed -n 's/^DB_VOLUME=//p' "$ROOT/deploy/compose.env" | tail -n 1)
T=$(new_tree volume-exists)
: > "$DOCKER_CALLS"
if STUB_VOLUMES="$VOLUME" "$T/scripts/local-compose-env.sh" >/dev/null 2>"$WORK/err"; then
  fail "generated a password although volume $VOLUME exists"
elif [ -e "$T/deploy/.env" ]; then
  fail "refused over an existing volume but still wrote deploy/.env"
elif ! grep -q "docker volume rm $VOLUME" "$WORK/err"; then
  fail "refusal does not say how to start over: $(cat "$WORK/err")"
else
  pass "an existing volume with no deploy/.env refuses, and says how to recover"
fi
if grep -qx "volume inspect $VOLUME" "$DOCKER_CALLS"; then
  pass "the guard checks the DB_VOLUME named in compose.env"
else
  fail "the guard did not inspect $VOLUME: $(cat "$DOCKER_CALLS")"
fi

T=$(new_tree volume-and-env)
echo "POSTGRES_PASSWORD=owned-by-this-checkout" > "$T/deploy/.env"
if STUB_VOLUMES="$VOLUME" "$T/scripts/local-compose-env.sh" >/dev/null \
  && [ "$(password_in "$T/deploy/.env")" = "owned-by-this-checkout" ]; then
  pass "an existing volume does not block a checkout that already has its password"
else
  fail "an existing volume blocked a checkout that already has its password"
fi

# --- missing compose.env fails without touching deploy/.env --------------------
T=$(new_tree nocompose)
rm "$T/deploy/compose.env"
echo "POSTGRES_PASSWORD=keep-me" > "$T/deploy/.env"
if "$T/scripts/local-compose-env.sh" >/dev/null 2>&1; then
  fail "script succeeded with no compose.env"
elif [ "$(cat "$T/deploy/.env")" = "POSTGRES_PASSWORD=keep-me" ]; then
  pass "a missing compose.env fails and leaves deploy/.env untouched"
else
  fail "a missing compose.env failed but rewrote deploy/.env"
fi

# --- no temp files left behind -------------------------------------------------
if ls "$WORK"/*/deploy/.env.* >/dev/null 2>&1; then
  fail "temp files left in deploy/: $(ls "$WORK"/*/deploy/.env.*)"
else
  pass "no temp files left behind"
fi

if [ "$FAILURES" -ne 0 ]; then
  echo "$FAILURES failure(s)"
  exit 1
fi
echo "all local-compose-env cases passed"
